def validate_draft(raw, facts):
    draft, used, notes = raw.get('draft'), raw.get('used_fact_ids'), raw.get('operator_notes', [])
    allowed = {fact['id'] for fact in facts}
    if (not isinstance(draft, str) or not draft.strip() or len(draft) > 3000
            or not isinstance(used, list) or any(not isinstance(x, str) or x not in allowed for x in used)
            or not isinstance(notes, list) or len(notes) > 10
            or any(not isinstance(note, str) or not note.strip() or len(note) > 500 for note in notes)):
        raise ProviderProblem('AI-черновик содержит неизвестные источники или неверный формат.', retryable=True)
    if re.search(r'не подтверждено\s*[—–-]\s*уточнить у ответственного', draft, re.IGNORECASE):
        raise ProviderProblem('AI поместил внутреннюю пометку в текст для клиента.', retryable=True)
    return draft.strip(), list(dict.fromkeys(used)), [note.strip() for note in notes]


def review_notes(data, notes):
    result = list(notes)
    if data['requires_human']:
        result.append('Проверьте предложенный шаг, применимость условий и полномочия. Черновик не одобряет возврат или компенсацию.')
    if data['confidence'] < 0.7:
        result.append('Классификация неоднозначна. Сверьте тональность и причины с текстом покупателя.')
    placeholders = list(dict.fromkeys(re.findall(r'\{\{([^{}]+)\}\}', data.get('draft', ''))))
    if placeholders:
        result.append('Заполните подтверждёнными данными перед отправкой: ' + ', '.join(placeholders) + '.')
    return list(dict.fromkeys(result))
